def hit(a,b,pad=12):
    return not (a[0]+a[2]/2+pad < b[0]-b[2]/2 or b[0]+b[2]/2+pad < a[0]-a[2]/2 or
                a[1]+a[3]/2+pad < b[1]-b[3]/2 or b[1]+b[3]/2+pad < a[1]-a[3]/2)
